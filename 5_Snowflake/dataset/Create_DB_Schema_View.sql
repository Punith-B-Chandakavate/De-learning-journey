USE SCHEMA SALES_DB.ANALYTICS_SCHEMA;

CREATE OR REPLACE VIEW MONTHLY_SALES AS
SELECT
    DATE_TRUNC('month', ORDER_DATE) AS ORDER_MONTH,
    SUM(QUANTITY * PRICE) AS TOTAL_REVENUE
FROM SALES_DB.RAW_SCHEMA.ORDER_RAW
GROUP BY 1
ORDER BY 1;


